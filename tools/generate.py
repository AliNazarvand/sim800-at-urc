def gen_dist(modules, categories, commands, urcs, data_version, manuals):
    DIST_DIR.mkdir(parents=True, exist_ok=True)
    meta = {
        "data_version": data_version,
        "manuals": manuals,
        "category_count": len(categories),
        "module_count": len(modules),
    }

    # JSON
    with (DIST_DIR / "at_commands.json").open("w", encoding="utf-8", newline="\n") as f:
        json.dump({"meta": meta, "commands": [_cmd_to_dict(c) for c in commands]},
                  f, indent=2, ensure_ascii=False)
        f.write("\n")
    with (DIST_DIR / "urcs.json").open("w", encoding="utf-8", newline="\n") as f:
        json.dump({"meta": meta, "urcs": [_urc_to_dict(u) for u in urcs]},
                  f, indent=2, ensure_ascii=False)
        f.write("\n")

    # CSV
    def _write_csv(path, rows, header):
        with path.open("w", encoding="utf-8", newline="") as f:
            w = csv.writer(f)
            w.writerow(header)
            for row in rows:
                w.writerow(row)

    cmd_header = ["Name", "Category", "Description", "Parameters",
                  "Responses", "Related URCs", "Supported Modules", "Manual Ref"]
    cmd_rows = []
    for c in commands:
        params = "; ".join(
            f"{p['name']}:{p['type']}:{p.get('values_or_range','')}"
            for p in (c.get("parameters") or [])
        )
        resps = " | ".join(c.get("responses") or [])
        rurcs = ", ".join(c.get("related_urcs") or [])
        if c.get("all_modules"):
            mods = "ALL"
        elif c.get("removed_after"):
            mods = f"REMOVED_AFTER={c['removed_after']}"
        else:
            mods = ", ".join(c.get("supported_on") or [])
        cmd_rows.append([c["name"], c["category"], c["description"],
                         params, resps, rurcs, mods, c["manual_ref"]])
    _write_csv(DIST_DIR / "at_commands.csv", cmd_rows, cmd_header)

    urc_header = ["Name", "Category", "Description", "Payload",
                  "Enabled By", "Supported Modules", "Manual Ref"]
    urc_rows = []
    for u in urcs:
        payload = " | ".join(u.get("payload") or [])
        eb = ", ".join(u.get("enabled_by") or [])
        if u.get("all_modules"):
            mods = "ALL"
        elif u.get("removed_after"):
            mods = f"REMOVED_AFTER={u['removed_after']}"
        else:
            mods = ", ".join(u.get("supported_on") or [])
        urc_rows.append([u["name"], u["category"], u["description"],
                         payload, eb, mods, u["manual_ref"]])
    _write_csv(DIST_DIR / "urcs.csv", urc_rows, urc_header)

    # Markdown
    def _md_escape(s):
        return str(s).replace("|", "\\|").replace("\n", " ")

    with (DIST_DIR / "at_commands.md").open("w", encoding="utf-8", newline="\n") as f:
        f.write("# AT Commands\n\n")
        f.write(f"Data version: {data_version}  \n")
        f.write(f"Manuals: {manuals}  \n")
        f.write(f"Total: {len(commands)}\n\n")
        f.write("| Name | Category | Description | Manual Ref |\n")
        f.write("|------|----------|-------------|------------|\n")
        for c in commands:
            f.write(f"| `{_md_escape(c['name'])}` | {_md_escape(c['category'])} | "
                    f"{_md_escape(c['description'])} | {_md_escape(c['manual_ref'])} |\n")

    with (DIST_DIR / "urcs.md").open("w", encoding="utf-8", newline="\n") as f:
        f.write("# URCs\n\n")
        f.write(f"Data version: {data_version}  \n")
        f.write(f"Manuals: {manuals}  \n")
        f.write(f"Total: {len(urcs)}\n\n")
        f.write("| Name | Category | Description | Enabled By | Manual Ref |\n")
        f.write("|------|----------|-------------|------------|------------|\n")
        for u in urcs:
            eb = ", ".join(u.get("enabled_by") or []) or "-"
            f.write(f"| `{_md_escape(u['name'])}` | {_md_escape(u['category'])} | "
                    f"{_md_escape(u['description'])} | {_md_escape(eb)} | "
                    f"{_md_escape(u['manual_ref'])} |\n")


def read_version():
    p = DATA_DIR / "VERSION"
    return p.read_text(encoding="utf-8").strip() if p.is_file() else "1.0.0"


def read_manuals():
    p = DATA_DIR / "MANUALS"
    return p.read_text(encoding="utf-8").strip() if p.is_file() else ""


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate SIM800 AT database artifacts.")
    ap.add_argument("--with-dist", action="store_true",
                    help="Also emit dist/ JSON, CSV and Markdown (off by default).")
    args = ap.parse_args()

    modules = load_yaml(DATA_DIR / "modules.yaml")
    categories = load_yaml(DATA_DIR / "categories.yaml")
    commands = load_yaml(DATA_DIR / "at_commands.yaml")
    urcs = load_yaml(DATA_DIR / "urcs.yaml")

    if len(categories) >= 0xFF:
        print("Too many categories; max 254 allowed.", file=sys.stderr)
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    files = {
        "at_types.hpp": gen_types(modules, categories),
        "at_commands.hpp": gen_commands(modules, categories, commands),
        "urcs.hpp": gen_urcs(modules, categories, urcs),
        "at_api.hpp": gen_api(modules, categories, commands, urcs),
    }

    changed = 0
    for name, content in files.items():
        if write_if_changed(OUT_DIR / name, content):
            print(f"  [write] {OUT_DIR / name}")
            changed += 1
        else:
            print(f"  [ok]    {OUT_DIR / name} (unchanged)")

    if args.with_dist:
        gen_dist(modules, categories, commands, urcs,
                 read_version(), read_manuals())
        print(f"  [dist]  {DIST_DIR}")

    print(f"generate.py: {changed} file(s) written.")
    return 0


if __name__ == "__main__":
    sys.exit(main())